GUN_USE_DURATION = 3200


def gun_item(weapon):
    wid = weapon["id"]
    is_shield = weapon.get("shield", False)
    cat_cn = {"ar": "突击步枪", "smg": "冲锋枪", "lmg": "轻机枪", "sg": "霰弹枪",
              "dmr": "精确射手步枪", "sniper": "狙击步枪", "pistol": "手枪",
              "shield": "护盾"}[weapon["cat"]]
    durability = {"max_durability": weapon["mag"] + 1} if not is_shield else None
    comps = {
        "minecraft:max_stack_size": {"value": 1},
        "minecraft:hand_equipped": {"value": True},
        "minecraft:icon": f"r6_{wid}",
        "minecraft:display_name": {"value": f"§f{weapon['name']} §8[{cat_cn}]"},
        "minecraft:use_modifiers": {"use_duration": GUN_USE_DURATION, "movement_modifier": 0.75},
        "minecraft:food": {"can_always_eat": True},
        "minecraft:tags": {"tags": ["minecraft:is_crossbow"]},
    }
    if durability:
        comps["minecraft:durability"] = durability
    return {"format_version": "1.20.50", "minecraft:item": {
        "description": {"identifier": f"{D.NAMESPACE}:{wid}",
                        "menu_category": {"category": "equipment"}},
        "components": comps,
    }}


