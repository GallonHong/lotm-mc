def gen_manifests():
    bp = {
        "format_version": 2,
        "header": {
            "name": D.PACK_NAME_BP,
            "description": D.PACK_DESC,
            "uuid": D.UUID_BP_HEADER,
            "version": D.PACK_VERSION,
            "min_engine_version": D.MIN_ENGINE,
        },
        "modules": [
            {"description": "Data Module", "type": "data", "uuid": D.UUID_BP_DATA,
             "version": D.PACK_VERSION},
            {"description": "Script Module", "type": "script", "language": "javascript",
             "entry": "scripts/main.js", "uuid": D.UUID_BP_SCRIPT, "version": D.PACK_VERSION},
        ],
        "dependencies": [
            {"module_name": "@minecraft/server", "version": D.SERVER_MODULE},
            {"module_name": "@minecraft/server-ui", "version": D.SERVER_UI_MODULE},
            {"uuid": D.UUID_RP_HEADER, "version": D.PACK_VERSION},
        ],
        "metadata": {"product_type": "addon"},
    }
    rp = {
        "format_version": 2,
        "header": {
            "name": D.PACK_NAME_RP,
            "description": D.PACK_DESC,
            "uuid": D.UUID_RP_HEADER,
            "version": D.PACK_VERSION,
            "min_engine_version": D.MIN_ENGINE,
        },
        "modules": [
            {"description": "Resource Module", "type": "resources", "uuid": D.UUID_RP_RES,
             "version": D.PACK_VERSION},
        ],
        "dependencies": [
            {"uuid": D.UUID_BP_HEADER, "version": D.PACK_VERSION},
        ],
        "metadata": {"product_type": "addon"},
    }
    write_json(os.path.join(BP, "manifest.json"), bp)
    write_json(os.path.join(RP, "manifest.json"), rp)


