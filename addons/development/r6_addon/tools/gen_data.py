def gen_items():
    items_dir = os.path.join(BP, "items")
    os.makedirs(items_dir, exist_ok=True)
    for weapon in D.WEAPONS:
        write_json(os.path.join(items_dir, f"{weapon['id']}.json"), gun_item(weapon))
    for gid, g in D.GADGETS.items():
        write_json(os.path.join(items_dir, f"{gid}.json"), gadget_item(gid, g))
    for item_id, m in D.MISC_ITEMS.items():
        write_json(os.path.join(items_dir, f"{item_id}.json"), misc_item(item_id, m))
    for op in D.OPERATORS:
        write_json(os.path.join(items_dir, f"op_{op['id']}.json"), badge_item(op))


