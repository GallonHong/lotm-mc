def gen_item_texture():
    data = {}
    for weapon in D.WEAPONS:
        data[f"r6_{weapon['id']}"] = {"textures": f"textures/items/guns/{weapon['art']}"}
    for gid, g in D.GADGETS.items():
        data[f"r6_{g['icon']}"] = {"textures": f"textures/items/gadgets/{g['icon']}"}
    for item_id, m in D.MISC_ITEMS.items():
        data[f"r6_{m['icon']}"] = {"textures": f"textures/items/misc/{m['icon']}"}
    for op in D.OPERATORS:
        data[f"r6_op_{op['id']}"] = {"textures": f"textures/items/badges/{op['id']}"}
    write_json(os.path.join(RP, "textures", "item_texture.json"), {
        "resource_pack_name": "r6_siege",
        "texture_name": "atlas.items",
        "texture_data": data,
    })


