def js(obj):
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":"))


def gen_registry():
    weapons = {}
    for w in D.WEAPONS:
        entry = dict(w)
        if not w.get("shield"):
            entry["interval"] = max(1, round(20 * 60 / w["rpm"]))
            entry["pellets"] = w.get("pellets", 1)
            entry["decay"] = w["decay"]
            entry["reserve"] = w["reserve"]
            entry["damage"] = round(w["damage"] * D.DAMAGE_SCALE, 3)
            entry["hs"] = w.get("hs", "instant")
            entry["maxDurability"] = w["mag"] + 1
            entry["soundId"] = f"r6.{w['sound']}_shoot"
            entry["auto"] = w["cat"] in ("ar", "smg", "lmg")
        weapons[w["id"]] = entry

    operators = []
    for op in D.OPERATORS:
        o = dict(op)
        o["badge"] = f"r6:op_{op['id']}"
        operators.append(o)

    gadgets = {}
    for gid, g in D.GADGETS.items():
        entry = dict(g)
        entry["item"] = f"r6:{gid}"
        gadgets[gid] = entry

    devices = {k: dict(v) for k, v in D.DEVICES.items()}

    lines = [
        "// " + GEN,
        f"export const NAMESPACE = {js(D.NAMESPACE)};",
        f"export const VERSION = {js('.'.join(str(x) for x in D.PACK_VERSION))};",
        f"DEFAULT_CONFIG = {js(D.DEFAULT_CONFIG)};",
    ]
    text = "\n".join([
        "// " + GEN,
        f"export const NAMESPACE = {js(D.NAMESPACE)};",
        f"export const VERSION = {js('.'.join(str(x) for x in D.PACK_VERSION))};",
        f"export const DEFAULT_CONFIG = {js(D.DEFAULT_CONFIG)};",
        f"export const WEAPONS = {js(weapons)};",
        f"export const OPERATORS = {js(operators)};",
        f"export const GADGETS = {js(gadgets)};",
        f"export const DEVICES = {js(devices)};",
        f"export const BLOCKS = {js({k: {'name': v['name'], 'en': v['en'],
                                         'id': f'{D.NAMESPACE}:{k}',
                                         'destructible': v['destructible'],
                                         'collision': v['collision']}
                                     for k, v in D.BLOCKS.items()})};",
        f"export const BARRIER_BLOCK = {js(D.BARRIER_BLOCK)};",
        f"export const FRAME_BLOCK = {js(D.FRAME_BLOCK)};",
        f"export const BARRIER_BLOCK_HP = {js(D.BARRIER_BLOCK_HP)};",
        f"export const ATTACKERS = {js([o['id'] for o in operators if o['side'] == 'attacker'])};",
        f"export const DEFENDERS = {js([o['id'] for o in operators if o['side'] == 'defender'])};",
        f"export const MISC_ITEMS = {js({k: {'name': v['name'], 'icon': v['icon'], 'desc': v['desc']} for k, v in D.MISC_ITEMS.items()})};",
        'export const weaponById = id => WEAPONS[id];',
        'export const operatorById = id => OPERATORS.find(o => o.id === id);',
        "",
    ])
    write_text(os.path.join(BP, "scripts", "data", "registry.js"), text)


def main():
    gen_manifests()
    gen_items()
    gen_item_texture()
    gen_entities()
    gen_blocks()
    gen_registry()
    print("generated manifests, %d items, %d blocks, entities, registry" %
          (len(D.WEAPONS) + len(D.GADGETS) + len(D.MISC_ITEMS) + len(D.OPERATORS),
           len(D.BLOCKS)))


if __name__ == "__main__":
    main()
