def bp_entity(device_id, d):
    family = d["family"]
    return {"format_version": "1.21.0", "minecraft:entity": {
        "description": {"identifier": f"{D.NAMESPACE}:{device_id}",
                        "is_spawnable": False, "is_summonable": True,
                        "is_experimental": False},
        "components": {
            "minecraft:type_family": {"family": [family, "r6_target", "inanimate"]},
            "minecraft:collision_box": {"width": 0.2, "height": 0.2},
            "minecraft:health": {"value": 100, "max": 100},
            "minecraft:physics": {"has_gravity": False, "has_collision": False},
            "minecraft:pushable": {"is_pushable": False, "is_pushable_by_piston": False},
            "minecraft:damage_sensor": {"triggers": [{"cause": "all", "deals_damage": False}]},
            "minecraft:knockback_resistance": {"value": 1.0},
            "minecraft:fire_immune": {},
            "minecraft:persistent": {},
        },
    }}


def rp_entity(device_id, d):
    return {"format_version": "1.10.0", "minecraft:client_entity": {
        "description": {
            "identifier": f"{D.NAMESPACE}:{device_id}",
            "materials": {"default": "entity_alphatest"},
            "textures": {"default": f"textures/entity/r6/{d['geo']}"},
            "geometry": {"default": f"geometry.r6.{d['geo']}"},
            "render_controllers": ["controller.render.default"],
        },
    }}


def geo_entry(d):
    w, h, dp = [max(2, int(round(v * 16))) for v in d["size"]]
    return {
        "description": {
            "identifier": f"geometry.r6.{d['geo']}",
            "texture_width": 128,
            "texture_height": 128,
            "visible_bounds_width": round(w / 16 + 1, 2),
            "visible_bounds_height": round(h / 16 + 1, 2),
            "visible_bounds_offset": [0, round(h / 32, 2), 0],
        },
        "bones": [{
            "name": "body",
            "pivot": [0, 0, 0],
            "cubes": [{
                "origin": [-w / 2, 0, -dp / 2],
                "size": [w, h, dp],
                "uv": [0, 0],
            }],
        }],
    }


def gen_entities():
    bp_ent_dir = os.path.join(BP, "entities")
    rp_ent_dir = os.path.join(RP, "entity")
    geos = []
    for device_id, d in D.DEVICES.items():
        write_json(os.path.join(bp_ent_dir, f"{device_id}.json"), bp_entity(device_id, d))
        write_json(os.path.join(rp_ent_dir, f"{device_id}.entity.json"), rp_entity(device_id, d))
        geos.append(geo_entry(d))
    write_json(os.path.join(RP, "models", "entity", "r6", "devices.geo.json"), {
        "format_version": "1.16.0",
        "minecraft:geometry": geos,
    })


